// Add npm scripts for testing
function addNpmScripts() {
  console.log('Adding npm scripts for testing...');
  
  try {
    const projectRoot = path.join(__dirname, '..');
    const packageJsonPath = path.join(projectRoot, 'package.json');
    
    if (!fs.existsSync(packageJsonPath)) {
      console.error('Error: package.json not found in project root.');
      return;
    }
    
    const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
    
    // Add or update test scripts
    packageJson.scripts = packageJson.scripts || {};
    
    const scriptsToAdd = {
      'test:registration': 'node tests/run_registration_tests.js',
      'test:setup': 'node tests/setup_test_environment.js',
      'test:all': 'jest --coverage'
    };
    
    let scriptsAdded = false;
    for (const [key, value] of Object.entries(scriptsToAdd)) {
      if (!packageJson.scripts[key]) {
        packageJson.scripts[key] = value;
        scriptsAdded = true;
      }
    }
    
    if (scriptsAdded) {
      fs.writeFileSync(packageJsonPath, JSON.stringify(packageJson, null, 2));
      console.log('Added npm scripts for testing.');
    } else {
      console.log('Test scripts already exist in package.json.');
    }
  } catch (error) {
    console.error('Error adding npm scripts:');
    console.error(error.message);
  }
  
  console.log('npm scripts setup complete.\n');
}

// Main function to run all setup steps
function main() {
  try {
    createDirectories();
    installDependencies();
    configureJest();
    createMockData();
    addNpmScripts();
    
    console.log('\n======================================');
    console.log('Test Environment Setup Complete');
    console.log('======================================');
    console.log('\nYou can now run the tests using:');
    console.log('npm run test:registration');
    console.log('\nOr run all tests with:');
    console.log('npm run test:all');
    console.log('\n======================================\n');
  } catch (error) {
    console.error('\nError setting up test environment:');
    console.error(error.message);
    process.exit(1);
  }
}

// Run the setup
main();